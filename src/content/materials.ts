export function getMaterial(slug: string) {
  return materials.find((m) => m.slug === slug);
}

export function formatPrice(priceFrom: number | null) {
  if (priceFrom === null) return "цена по расчёту";
  return `от ${new Intl.NumberFormat("ru-RU").format(priceFrom)} ₸/м²`;
}

export function getMaterialSpecs(m: Material) {
  return [
    { label: "Система", value: m.system },
    { label: "Применение", value: m.application },
    { label: "Срок службы", value: m.lifespan, mono: true },
    { label: "Подконструкция", value: m.subframe },
    { label: "Горючесть", value: m.fire },
    { label: "Монтаж зимой", value: m.winter },
    { label: "Стоимость", value: formatPrice(m.priceFrom), mono: true },
  ];
}

export function getRelatedMaterials(slug: string, count = 3) {
  const i = materials.findIndex((m) => m.slug === slug);
  return Array.from({ length: count }, (_, k) => materials[(i + 1 + k) % materials.length]!).filter(
    (m) => m.slug !== slug,
  );
}
